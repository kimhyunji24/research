"""Copy every table/figure float of a full manuscript into its own file, so the short version reuses them unchanged.

    python3 scripts/2026-10-21/extract_floats.py en   # paper/main_en.tex -> paper/floats_en/<label>.tex
    python3 scripts/2026-10-21/extract_floats.py ko   # paper/main_ko.tex -> paper/floats_ko/<label>.tex

The full manuscript stays the single source: rerun after editing it. Placement options are normalised to [htbp]
so a float can sit in the main text or the appendix of the short version.
"""
import io
import os
import re
import sys

lang = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = os.path.join(ROOT, "paper", f"main_{lang}.tex")
out = os.path.join(ROOT, "paper", f"floats_{lang}")
os.makedirs(out, exist_ok=True)
t = io.open(src, encoding="utf-8").read()
blocks = re.findall(r"\\begin\{(table|figure)\}(\[[^]]*\])?(.*?)\\end\{\1\}", t, flags=re.S)
seen = []
for kind, _opt, inner in blocks:
    lab = re.search(r"\\label\{((?:tab|fig):[^}]*)\}", inner).group(1)
    name = lab.replace(":", "_")
    body = f"% Generated by scripts/2026-10-21/extract_floats.py from paper/main_{lang}.tex; edit the full manuscript, not this file.\n" \
           f"\\begin{{{kind}}}[htbp]{inner}\\end{{{kind}}}\n"
    io.open(os.path.join(out, name + ".tex"), "w", encoding="utf-8", newline="\n").write(body)
    seen.append(name)
print(len(seen), "floats:", " ".join(seen))
